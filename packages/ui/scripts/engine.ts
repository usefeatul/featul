/** Regenerate with: bun packages/ui/scripts/engine.ts (after changing lib/engine.ts or lib/dither.ts) */
import { unlinkSync, writeFileSync } from "node:fs";

const entry = new URL("./engine-entry.ts", import.meta.url).pathname;
writeFileSync(
  entry,
  `import { startDitherEngine } from "../src/lib/engine";\nstartDitherEngine();\n`,
);
const result = await Bun.build({
  entrypoints: [entry],
  minify: true,
  format: "iife",
  target: "browser",
});
unlinkSync(entry);
if (!result.success) throw new AggregateError(result.logs, "engine build failed");
const code = (await result.outputs[0]!.text()).trim();
writeFileSync(
  new URL("../src/lib/engine-script.ts", import.meta.url),
  `// Generated by scripts/engine.ts. Do not edit by hand.\nexport const ditherEngineScript = ${JSON.stringify(code)};\n`,
);
console.log(`engine script: ${code.length} bytes`);
